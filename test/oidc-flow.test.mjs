import test from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync, createHash } from 'node:crypto';
import request from 'supertest';
import { createApp } from '../src/app.mjs';
import { createSqliteAdapter } from '../src/oidc-adapter.mjs';
import { ChallengeStore } from '../src/challenge-store.mjs';
import { AccountStore } from '../src/accounts.mjs';

test('discovery and email verification establish an OIDC authorization', async () => {
 const issuer='http://127.0.0.1:31234';
 const {privateKey}=generateKeyPairSync('rsa',{modulusLength:2048});
 const jwk=privateKey.export({format:'jwk'}); jwk.kid='test-key'; jwk.use='sig'; jwk.alg='RS256';
 const store=createSqliteAdapter(':memory:'); const accounts=new AccountStore(':memory:'); const challenges=new ChallengeStore(':memory:','0123456789abcdef0123456789abcdef');
 let sent; const {app}=createApp({issuer, clients:[{client_id:'demo',client_secret:'secret-secret-secret-secret-secret',redirect_uris:['http://localhost:4400/callback'],response_types:['code'],grant_types:['authorization_code'],token_endpoint_auth_method:'client_secret_basic'}],jwks:{keys:[jwk]},cookieKeys:['0123456789abcdef0123456789abcdef'],adapter:store.Adapter,accounts,challenges,sendCode:async(email,code)=>{sent={email,code};}});
 const agent=request.agent(app);
 const discovery=await agent.get('/.well-known/openid-configuration').expect(200); assert.equal(discovery.body.issuer,issuer);
 const verifier='a'.repeat(64), challenge=createHash('sha256').update(verifier).digest('base64url');
 const auth=await agent.get('/auth').query({client_id:'demo',redirect_uri:'http://localhost:4400/callback',response_type:'code',scope:'openid email',state:'state',code_challenge:challenge,code_challenge_method:'S256'}).expect(303);
 let path=new URL(auth.headers.location,issuer).pathname;
 await agent.get(path).expect(200);
 await agent.post(path+'/send').set('Origin','https://evil.example').type('form').send({email:'person@EXAMPLE.TEST'}).expect(403);
 await agent.post(path+'/send').set('Origin',issuer).type('form').send({email:'person@EXAMPLE.TEST'}).expect(200);
 assert.equal(sent.email,'person@example.test');
 const verified=await agent.post(path+'/verify').set('Origin',issuer).type('form').send({code:sent.code}).expect(303);
 assert.ok(verified.headers.location);
 let next=await agent.get(new URL(verified.headers.location,issuer).pathname+new URL(verified.headers.location,issuer).search).expect(303);
 path=new URL(next.headers.location,issuer).pathname;
 await agent.get(path).expect(200);
 const consent=await agent.post(path+'/consent').set('Origin',issuer).type('form').send({}).expect(303);
 const resume=new URL(consent.headers.location,issuer); next=await agent.get(resume.pathname+resume.search).expect(303);
 const callback=new URL(next.headers.location); assert.equal(callback.searchParams.get('state'),'state'); assert.ok(callback.searchParams.get('code'));
 const token=await request(app).post('/token').auth('demo','secret-secret-secret-secret-secret').type('form').send({grant_type:'authorization_code',code:callback.searchParams.get('code'),redirect_uri:'http://localhost:4400/callback',code_verifier:verifier}).expect(200);
 const info=await request(app).get('/me').set('Authorization',`Bearer ${token.body.access_token}`).expect(200);
 assert.equal(info.body.email,'person@example.test'); assert.equal(info.body.email_verified,true); assert.ok(info.body.sub);
 await request(app).post('/token').auth('demo','secret-secret-secret-secret-secret').type('form').send({grant_type:'authorization_code',code:callback.searchParams.get('code'),redirect_uri:'http://localhost:4400/callback',code_verifier:verifier}).expect(400);
 accounts.disable(info.body.sub); await request(app).get('/me').set('Authorization',`Bearer ${token.body.access_token}`).expect(401);
 store.close(); accounts.close(); challenges.close();
});
